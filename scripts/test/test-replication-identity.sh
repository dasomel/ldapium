#!/usr/bin/env bash
# Unified live verification of the dedicated replication identity (docs/changes/replication-identity,
# #353, T-020..T-024): the assertion table for CHANGE.md experiments E1-E17. Real slapd, real
# entrypoint, real operator command, verified TLS; nothing is mocked.
#
# This script adds what the dedicated per-feature tests do not cover and points at them for the rest
# (the table is printed at the end and kept in EVIDENCE.md). Every check label starts with the
# experiment tag it replaces, e.g. "[E3]".
#
#   cluster  3 nodes (LDAP_SIZE_LIMIT=5, accesslog on): admin -> prepare -> operator `ensure` ->
#            rolling dedicated. E2 negatives on the REAL entry (policy-allowed self password,
#            pwd* operational attributes, accesslog, plaintext, ordinary user), E5 limits, E3 lock
#            matrix (5 variants + 2 controls), E13 `-Y EXTERNAL` with a client certificate whose
#            subject is the reserved DN, E17 delegation default + SASL negatives, E11 check under
#            sustained writes (contrast + 4 injected defects), rotation R0 (lock variant 5, stale
#            consumer fingerprint), E10 rollback through `rollback-admin` with mixed modes.
#   chaos    (needs the cluster) hard kill of a consumer under writes, network partition of a
#            consumer with writes on both sides, identity binds throughout, no err=49.
#   pair     E8 contrast (admin mode, wiped sid 1, wrong LDAP_REPLICATION_PASSWORD loses the peer's data) and
#            E1/E10 (a dedicated consumer of a provider WITHOUT the prepare ACL silently loses
#            userPassword; the check catches it; prepare + wipe repairs it).
#   proxy    E17 contrast: with olcAuthzPolicy=to and an authzTo entry an ordinary user reads the
#            administrator hash as the identity; prepare then refuses to start.
#
# Covered by sibling tests (not repeated here): test-replication-identity-env.sh,
# -prepare.sh (E14, E4 plaintext/ssf), -dedicated.sh (E4 rogue provider, E9, E12, E13 stored-config
# refusals, E16), -ensure.sh, -reconcile.sh, -restore.sh (D63, E6/E7 restore), -rotate.sh (E6, E7),
# -rollback-admin.sh (D66), test-replication-identity-check*.{py,sh}.
#
# Usage: scripts/test/test-replication-identity.sh [image]
#   image defaults to ldapium:e2e (ldapium:chaos in replication-chaos-e2e.yml). Requires Docker.
#   RIDU_TIMEOUT (seconds, default 120) bounds every wait. RIDU_ONLY=cluster|chaos|pair|proxy runs
#   one part (chaos includes the cluster setup). Resources are named ldapium-ridu-* and only those
#   are removed on exit.
set -euo pipefail
# Never pipe into `grep -q` (SIGPIPE + pipefail): match captured variables.

image="${1:-ldapium:e2e}"
here="$(cd "$(dirname "$0")/.." && pwd)"
timeout_s="${RIDU_TIMEOUT:-120}"
only="${RIDU_ONLY:-all}"
suffix="$$"
pw="riduAdminPw-Zq7Lm2Xv9Kd4Hs8Wt1Bn6Rc3Yf5Ug0Pe"
badpw="riduWrongPw-Xc8Vb2Nm5Qa1Ws4Ed7Rf0Tg3Yh6Uj9"
alicepw="riduAlicePw-1"
base="dc=example,dc=org"
admin="cn=admin,${base}"
iddn="cn=replicator,${base}"
poldn="cn=replication-policy,${base}"
net="ldapium-ridu-net-${suffix}"
n1="ldapium-ridu-n1-${suffix}"
n2="ldapium-ridu-n2-${suffix}"
n3="ldapium-ridu-n3-${suffix}"
pa="ldapium-ridu-pa-${suffix}"
pc="ldapium-ridu-pc-${suffix}"
px="ldapium-ridu-px-${suffix}"
certs="ldapium-ridu-certs-${suffix}"
work="$(mktemp -d)"
cur_peers="ldaps://${n1}:636,ldaps://${n2}:636,ldaps://${n3}:636"
idfile=idold            # file in the certs volume holding the CURRENT identity credential
load_pid=""
size_limit=5           # the cluster part runs with a tiny limit (E5); pair and proxy keep the image default
rot_pw=""              # the rotation credential generated by rotate (lost with a container, restored by tools)

fail=0
tags="$work/tags"
: > "$tags"
ok() { printf 'PASS: %s\n' "$1"; local t; t="$(grep -o '^\[E[0-9]*\]' <<<"$1" || true)"; [ -z "$t" ] || printf '%s\n' "$t" >> "$tags"; }
bad() { printf 'FAIL: %s\n' "$1" >&2; fail=1; }
check() { if [ "$2" = "$3" ]; then ok "$1"; else bad "$1: expected '$2', got '$3'"; fi; }
short() { local s="${1#ldapium-ridu-}"; printf '%s' "${s%-"${suffix}"}"; }
# check_run: like check, and on a mismatch shows the captured output of the last command (counts only)
check_run() { if [ "$2" = "$3" ]; then ok "$1"; else bad "$1: expected '$2', got '$3'"; printf '%s\n' "$last_out" | head -n 12 >&2; fi; }
has() { case "$2" in *"$1"*) return 0 ;; *) return 1 ;; esac; } # needle haystack
want() { [ "$only" = all ] || [ "$only" = "$1" ]; }
want_cluster() { [ "$only" = all ] || [ "$only" = cluster ] || [ "$only" = chaos ]; }

reg_containers=("$n1" "$n2" "$n3" "$pa" "$pc" "$px")
reg_vols=("${n1}-cfg" "${n1}-data" "${n2}-cfg" "${n2}-data" "${n3}-cfg" "${n3}-data"
  "${pa}-cfg" "${pa}-data" "${pc}-cfg" "${pc}-data" "${px}-cfg" "${px}-data" "$certs")
# shellcheck disable=SC2317,SC2329 # invoked via the trap below
cleanup() {
  local x rc=$?
  trap - EXIT
  rm -f "$work/load.run"
  [ -z "$load_pid" ] || kill "$load_pid" 2>/dev/null || true
  if [ "$rc" != 0 ]; then docker logs "$n1" 2>&1 | tail -n 15 >&2 || true; fi
  for x in "${reg_containers[@]}"; do docker rm -fv "$x" >/dev/null 2>&1 || true; done
  for x in "${reg_vols[@]}"; do docker volume rm -f "$x" >/dev/null 2>&1 || true; done
  docker network rm "$net" >/dev/null 2>&1 || true
  rm -rf "$work"
  exit "$rc"
}
trap cleanup EXIT
trap 'exit 130' INT
trap 'exit 143' TERM

poll() { local w=0; until "$@" >/dev/null 2>&1; do sleep 1; w=$((w + 1)); [ "$w" -lt "$timeout_s" ] || return 1; done; }
# shellcheck disable=SC2317,SC2329 # invoked through poll
ready() { docker exec "$1" ldapwhoami -x -H ldap://localhost >/dev/null 2>&1; }
# asearch fails unless ldapsearch exits 0: an empty result of a FAILED search never reads as "absent".
asearch() { local n="$1"; shift; docker exec "$n" ldapsearch -x -LLL -o ldif-wrap=no -H ldap://localhost -D "$admin" -w "$pw" "$@"; }
amodify() { docker exec -i "$1" ldapmodify -e relax -x -H ldap://localhost -D "$admin" -w "$pw" >/dev/null; }
cmodify() { docker exec -i "$1" ldapmodify -x -H ldap://localhost -D cn=admin,cn=config -w "$pw" >/dev/null; }
# shellcheck disable=SC2317,SC2329 # invoked through poll
has_uid() { local o; o="$(asearch "$1" -b "$base" "(uid=$2)" uid)" || return 1; has "uid: $2" "$o"; }
# shellcheck disable=SC2317,SC2329 # invoked through poll
lacks_uid() { local o; o="$(asearch "$1" -b "$base" "(uid=$2)" uid)" || return 1; ! has "uid: $2" "$o"; }
# shellcheck disable=SC2317,SC2329 # invoked through poll
has_identity() { local o; o="$(asearch "$1" -b "$iddn" -s base cn)" || return 1; has "cn: replicator" "$o"; }
uid_count() { local o; o="$(asearch "$1" -b "$base" '(objectClass=inetOrgPerson)' uid)" || { echo "?"; return; }; grep -c '^uid: ' <<<"$o" || true; }
# attribute value count of a base-scope read; "?" when the read itself failed
vcount() { local o; o="$(asearch "$1" -b "$2" -s base "$3")" || { echo "?"; return; }; grep -c -i "^$3::\? " <<<"$o" || true; }
hash_of() { local o; o="$(asearch "$1" -b "$base" "(uid=$2)" userPassword)" || return 1; sed -n 's/^userPassword:: *//p;s/^userPassword: *//p' <<<"$o" | head -n 1; }
add_user() { # node uid
  docker exec -i "$1" ldapadd -x -H ldap://localhost -D "$admin" -w "$pw" >/dev/null <<EOF
dn: uid=$2,${base}
objectClass: inetOrgPerson
uid: $2
cn: $2
sn: $2
userPassword: ${alicepw}
EOF
}
err49() { local o; o="$(docker logs "$1" 2>&1)"; grep -c 'err=49' <<<"$o" || true; }
cfg_dump() { docker exec "$1" slapcat -n 0 -o ldif-wrap=no; }
syncrepl_binds() { local o; o="$(cfg_dump "$1")" || { echo "?"; return; }; grep -c "^olcSyncrepl:.*binddn=\"$2\"" <<<"$o" || true; }
last_out=""; last_rc=0
run() { last_rc=0; last_out="$("$@" 2>&1)" || last_rc=$?; printf '%s\n' "$last_out" >> "$work/all.out"; }
tlsx() { local n="$1"; shift; docker exec -i -e LDAPTLS_CACERT=/certs/ca.pem "$n" "$@"; }
idbind() { local x=0; tlsx "$1" ldapwhoami -x -H "ldaps://$1:636" -D "$iddn" -y "/certs/$2" >/dev/null 2>&1 || x=$?; echo "$x"; }

# start_node <name> <sid> <mode> [docker args...]; mode: admin | prepare | file:<name in the certs volume>
start_node() {
  local name="$1" sid="$2" mode="$3" args=()
  shift 3
  case "$mode" in
    prepare) args+=(-e LDAP_REPLICATION_IDENTITY=prepare) ;;
    file:*) args+=(-e LDAP_REPLICATION_IDENTITY=dedicated -e "LDAP_REPLICATION_PASSWORD_FILE=/certs/${mode#file:}") ;;
  esac
  docker run -d --name "$name" --network "$net" --hostname "$name" \
    -v "${name}-cfg:/etc/openldap/slapd.d" -v "${name}-data:/var/lib/openldap/data" \
    -v "${certs}:/certs:ro" -e LDAP_TLS_ENABLED=true -e LDAP_TLS_CERT_FILE=/certs/c.pem \
    -e LDAP_TLS_KEY_FILE=/certs/k.pem -e LDAP_TLS_CA_FILE=/certs/ca.pem \
    -e LDAP_ROOT_DN="$base" -e LDAP_ADMIN_PASSWORD="$pw" \
    -e LDAP_SIZE_LIMIT="$size_limit" -e LDAP_ACCESSLOG_ENABLED=true \
    -e LDAP_REPLICATION_ENABLED=true -e LDAP_SERVER_ID="$sid" \
    -e LDAP_REPLICATION_PEERS="$cur_peers" ${args[@]+"${args[@]}"} "$@" "$image" >/dev/null
}
sid_of() { case "$1" in "$n1" | "$pa" | "$px") echo 1 ;; "$n2" | "$pc") echo 2 ;; *) echo 3 ;; esac; }
tools() { # the operator script and the administrator password file (lost with every container)
  docker cp "${here}/replication-identity.sh" "${1}:/tmp/ri.sh"
  printf '%s' "$pw" | docker exec -i "$1" sh -c 'umask 077; cat > /tmp/admin.pw'
  [ -z "$rot_pw" ] || printf '%s' "$rot_pw" | docker exec -i "$1" sh -c 'umask 077; cat > /tmp/new.pw'
}
boot() { # name mode [docker args...]: (re)create the container on its volumes and wait for it
  local name="$1" mode="$2"
  shift 2
  docker rm -f "$name" >/dev/null 2>&1 || true
  start_node "$name" "$(sid_of "$name")" "$mode" "$@"
  poll ready "$name" || { bad "$(short "$name") (${mode}) never ready"; docker logs "$name" 2>&1 | tail -n 20 >&2; exit 1; }
  tools "$name"
}
wipe_node() { docker rm -f "$1" >/dev/null 2>&1 || true; docker volume rm -f "${1}-cfg" "${1}-data" >/dev/null; docker volume create "${1}-cfg" >/dev/null; docker volume create "${1}-data" >/dev/null; }
put_secret() { printf '%s' "$2" | docker run --rm -i --user 0 -v "${certs}:/certs" --entrypoint sh "$image" -c 'cat > "/certs/$1"; chown 999:999 "/certs/$1"; chmod 600 "/certs/$1"' sh "$1"; }
# ri <node> <args...>: the operator command inside <node>. rip adds every other cluster node as --peer.
ri() { local n="$1"; shift; docker exec -e LDAPTLS_CACERT=/certs/ca.pem "$n" bash /tmp/ri.sh "$@" --uri "ldaps://${n}:636" --base "$base" --admin-password-file /tmp/admin.pw; }
rip() { local n="$1" x peerargs=(); shift; for x in "$n1" "$n2" "$n3"; do [ "$x" = "$n" ] || peerargs+=(--peer "ldaps://${x}:636"); done; ri "$n" "$@" "${peerargs[@]}"; }
peer_check() { # extra args: selected-node check from n1 over n2 and n3
  "${here}/check-replication-identity.sh" --container "$n1" --uri "ldaps://${n1}:636" \
    --peer "ldaps://${n2}:636" --peer "ldaps://${n3}:636" --base "$base" \
    --admin-password-file /certs/adminpw --identity-password-file "/certs/${idfile}" --ca-file /certs/ca.pem "$@"
}
bulk_users() { # node count: u01..uNN in one add
  local i
  for i in $(seq 1 "$2"); do
    printf 'dn: uid=u%02d,%s\nobjectClass: inetOrgPerson\nuid: u%02d\ncn: u%02d\nsn: u%02d\nuserPassword: %s\n\n' "$i" "$base" "$i" "$i" "$i" "$alicepw"
  done | docker exec -i "$1" ldapadd -x -H ldap://localhost -D "$admin" -w "$pw" >/dev/null
}
load_start() { # ~3 writes/s to entries the check does not compare (description), as in E11
  : > "$work/load.run"; : > "$work/load.ok"
  (
    local i=0
    while [ -e "$work/load.run" ]; do
      i=$((i + 1))
      if docker exec -i "$n1" ldapmodify -x -H ldap://localhost -D "$admin" -w "$pw" >/dev/null 2>&1 <<EOF
dn: uid=u0$((i % 3 + 1)),${base}
changetype: modify
replace: description
description: load-${i}
EOF
      then echo ok >> "$work/load.ok"; fi
      sleep 0.2
    done
  ) &
  load_pid=$!
}
load_stop() { # a load that never wrote anything must not read as "check passed under load"
  rm -f "$work/load.run"; [ -z "$load_pid" ] || wait "$load_pid" 2>/dev/null || true; load_pid=""
  [ "$(wc -l < "$work/load.ok")" -ge 5 ] || bad "load generator completed fewer than 5 writes ($(wc -l < "$work/load.ok"))"
}

docker network create "$net" >/dev/null
for x in "${reg_vols[@]}"; do docker volume create "$x" >/dev/null; done

# Throwaway CA; one server certificate for every node name (verified by name); a CLIENT certificate
# whose subject is the reserved DN (E13); password files for the check script (a single-file bind
# mount is unreadable for uid 999 on Colima, hence a named volume, AGENTS.md).
docker run --rm --user 0 -v "${certs}:/certs" --entrypoint sh "$image" -c '
set -e
cd /certs
printf "subjectAltName=DNS:%s,DNS:%s,DNS:%s,DNS:%s,DNS:%s,DNS:%s,DNS:localhost\n" "$1" "$2" "$3" "$4" "$5" "$6" > ext.cnf
openssl req -x509 -newkey rsa:2048 -nodes -keyout ca.key -out ca.pem -days 2 -subj /CN=ridu-ca
openssl req -newkey rsa:2048 -nodes -keyout k.pem -out s.csr -subj /CN=localhost
openssl x509 -req -in s.csr -CA ca.pem -CAkey ca.key -CAcreateserial -out c.pem -days 2 -extfile ext.cnf
openssl req -newkey rsa:2048 -nodes -keyout idk.pem -out idc.csr -subj /DC=org/DC=example/CN=replicator
openssl x509 -req -in idc.csr -CA ca.pem -CAkey ca.key -CAcreateserial -out idc.pem -days 2
printf "%s" "$7" > adminpw
printf "%s" "$8" > badpw
chown -R 999:999 /certs
chmod 600 k.pem ca.key idk.pem adminpw badpw
' sh "$n1" "$n2" "$n3" "$pa" "$pc" "$px" "$pw" "$badpw" >/dev/null 2>&1

# ============================================================================
# cluster setup: admin -> prepare -> operator ensure -> rolling dedicated
# ============================================================================
if want_cluster; then
  echo "== setup: 3 nodes (size limit 5, accesslog on): admin -> prepare -> ensure -> dedicated"
  boot "$n1" admin
  boot "$n2" admin
  boot "$n3" admin
  bulk_users "$n1" 12
  add_user "$n1" alice
  for n in "$n2" "$n3"; do poll has_uid "$n" alice || bad "admin cluster: alice never reached $(short "$n")"; done
  for n in "$n1" "$n2" "$n3"; do boot "$n" prepare; done
  run ri "$n1" ensure --out /tmp/idpw
  check "ensure creates the policy and the identity" 0 "$last_rc"
  put_secret idold "$(docker exec "$n1" cat /tmp/idpw)"
  for n in "$n2" "$n3"; do poll has_identity "$n" || bad "identity never replicated to $(short "$n")"; done
  for n in "$n2" "$n3" "$n1"; do boot "$n" file:idold; done
  for n in "$n1" "$n2" "$n3"; do
    check "setup: $(short "$n") consumers bind as the identity, none as the admin DN" "2:0" "$(syncrepl_binds "$n" "$iddn"):$(syncrepl_binds "$n" "$admin")"
  done
  add_user "$n2" dave
  for n in "$n1" "$n3"; do poll has_uid "$n" dave || bad "dedicated: dave never reached $(short "$n")"; done
  check "setup: 14 users on every node (the identity is not bound by the size limit)" "14:14:14" "$(uid_count "$n1"):$(uid_count "$n2"):$(uid_count "$n3")"
fi

if want cluster; then
  echo "== E2 / E5: the identity can read everything and write nothing; ordinary users are unchanged"
  idtls() { tlsx "$n1" "$@"; } # -i for stdin
  ldap_rc() { local x=0; "$@" >/dev/null 2>&1 || x=$?; echo "$x"; }
  idmod() { idtls ldapmodify -x -H "ldaps://${n1}:636" -D "$iddn" -y "/certs/${idfile}"; }
  check "[E2] the identity reads another user's userPassword hash over TLS" 1 \
    "$(idtls ldapsearch -x -LLL -H "ldaps://${n1}:636" -D "$iddn" -y "/certs/${idfile}" -b "$base" '(uid=alice)' userPassword | grep -c '^userPassword' || true)"
  check "[E5] the identity's search is not cut by the size limit of 5 (14 users)" 14 \
    "$(idtls ldapsearch -x -LLL -H "ldaps://${n1}:636" -D "$iddn" -y "/certs/${idfile}" -b "$base" '(objectClass=inetOrgPerson)' uid | grep -c '^uid:' || true)"
  check "[E5] control: an ordinary user is cut by the same limit (ldap rc 4)" 4 \
    "$(ldap_rc idtls ldapsearch -x -LLL -H "ldaps://${n1}:636" -D "uid=alice,${base}" -w "$alicepw" -b "$base" '(objectClass=inetOrgPerson)' uid)"
  for attr in description pwdEndTime pwdAccountLockedTime pwdPolicySubentry; do
    val="x"; [ "$attr" = pwdPolicySubentry ] && val="$poldn"; [ "$attr" = pwdEndTime ] && val="20990101000000Z"; [ "$attr" = pwdAccountLockedTime ] && val="000001010000Z"
    check "[E2] identity cannot write its own ${attr} (50)" 50 \
      "$(ldap_rc idmod <<EOF
dn: ${iddn}
changetype: modify
replace: ${attr}
${attr}: ${val}
EOF
)"
  done
  # self password change: refused by the ACL, also when the policy would allow it (pwdAllowUserChange TRUE)
  chg_pw() { idmod <<EOF
dn: ${iddn}
changetype: modify
replace: userPassword
userPassword: ${alicepw}-self
EOF
  }
  check "[E2] identity cannot change its own password (50)" 50 "$(ldap_rc chg_pw)"
  amodify "$n1" <<EOF
dn: ${poldn}
changetype: modify
replace: pwdAllowUserChange
pwdAllowUserChange: TRUE
EOF
  check "[E2] ... also when the policy allows user changes (still 50)" 50 "$(ldap_rc chg_pw)"
  amodify "$n1" <<EOF
dn: ${poldn}
changetype: modify
replace: pwdAllowUserChange
pwdAllowUserChange: FALSE
EOF
  check "[E2] identity cannot delete itself (50)" 50 "$(ldap_rc idtls ldapdelete -x -H "ldaps://${n1}:636" -D "$iddn" -y "/certs/${idfile}" "$iddn")"
  check "[E2] identity cannot add an entry (50)" 50 \
    "$(ldap_rc idtls ldapadd -x -H "ldaps://${n1}:636" -D "$iddn" -y "/certs/${idfile}" <<EOF
dn: uid=evil,${base}
objectClass: inetOrgPerson
uid: evil
cn: evil
sn: evil
EOF
)"
  check "[E2] identity cannot modify another entry (50)" 50 \
    "$(ldap_rc idmod <<EOF
dn: uid=alice,${base}
changetype: modify
replace: description
description: x
EOF
)"
  check "[E2] identity cannot read cn=config (32)" 32 "$(ldap_rc idtls ldapsearch -x -LLL -H "ldaps://${n1}:636" -D "$iddn" -y "/certs/${idfile}" -b cn=config -s base)"
  acc=0; o="$(idtls ldapsearch -x -LLL -H "ldaps://${n1}:636" -D "$iddn" -y "/certs/${idfile}" -b cn=accesslog -s sub reqType 2>&1)" || acc=$?
  check "[E2] identity cannot read cn=accesslog (no record, non-zero)" "no:yes" "$(has 'reqType' "$o" && echo yes || echo no):$([ "$acc" != 0 ] && echo yes || echo no)"
  o="$(docker exec -e LDAPTLS_CACERT=/certs/ca.pem "$n1" ldapsearch -x -LLL -H ldap://localhost -D "$iddn" -y "/certs/${idfile}" -b "$base" '(uid=alice)' userPassword uid 2>&1 || true)"
  check "[E2] over plaintext the identity gets no entry and no hash (ssf=128)" "0:0" "$(grep -c '^uid:' <<<"$o" || true):$(grep -c '^userPassword' <<<"$o" || true)"
  check "[E2] an ordinary user cannot modify the identity entry (50)" 50 \
    "$(ldap_rc docker exec -i "$n1" ldapmodify -x -H ldap://localhost -D "uid=alice,${base}" -w "$alicepw" <<EOF
dn: ${iddn}
changetype: modify
replace: description
description: x
EOF
)"
  check "[E2] regression: an ordinary user still changes her own description and binds" "0:0" \
    "$(ldap_rc docker exec -i "$n1" ldapmodify -x -H ldap://localhost -D "uid=alice,${base}" -w "$alicepw" <<EOF
dn: uid=alice,${base}
changetype: modify
replace: description
description: mine
EOF
):$(ldap_rc docker exec "$n1" ldapwhoami -x -H ldap://localhost -D "uid=alice,${base}" -w "$alicepw")"
  check "[E2] the refused writes changed nothing (no evil, identity entry intact)" "absent:yes" \
    "$(lacks_uid "$n1" evil && echo absent || echo present-or-failed):$(has_identity "$n1" && echo yes || echo no)"
fi

if want cluster; then
  echo "== E13 / E17: no SASL or delegation path reaches the identity"
  ext() { docker exec -i -e LDAPTLS_CACERT=/certs/ca.pem -e LDAPTLS_CERT=/certs/idc.pem -e LDAPTLS_KEY=/certs/idk.pem "$n1" "$@"; }
  cert_subject="$(docker run --rm -v "${certs}:/certs:ro" --entrypoint openssl "$image" x509 -in /certs/idc.pem -noout -subject -nameopt RFC2253)"
  check "[E13] the client certificate's subject is the reserved DN" "subject=CN=replicator,DC=example,DC=org" "$cert_subject"
  check "[E13] TLS only: olcTLSVerifyClient is not set to a client-authenticating value" "0" \
    "$(cfg_dump "$n1" | grep -c -i -E '^olcTLSVerifyClient: (allow|try|demand|hard|true|yes)' || true)"
  run ext ldapwhoami -Y EXTERNAL -H "ldaps://${n1}:636"
  check "[E13] -Y EXTERNAL with that certificate fails (rc 7, mechanism not supported)" "7:no" "${last_rc}:$(has 'replicator' "$last_out" && echo yes || echo no)"
  run ext ldapsearch -Y EXTERNAL -LLL -H "ldaps://${n1}:636" -b "$base" '(uid=alice)' userPassword
  check "[E13] ... and reads no hash with it" "0" "$(grep -c '^userPassword' <<<"$last_out" || true)"
  run docker exec "$n1" ldapwhoami -Y EXTERNAL -H ldapi://%2Fvar%2Flib%2Fopenldap%2Frun%2Fldapi
  check "[E13] control: -Y EXTERNAL does work over ldapi (peer credentials)" "0" "$last_rc"
  run ext ldapwhoami -x -H "ldaps://${n1}:636" -D "$iddn" -y "/certs/${idfile}"
  check "[E13] control: the same certificate does not disturb the simple bind of the identity" "0" "$last_rc"
  for mech in DIGEST-MD5 CRAM-MD5 PLAIN; do
    run tlsx "$n1" ldapwhoami -Y "$mech" -U replicator -y "/certs/${idfile}" -H "ldaps://${n1}:636"
